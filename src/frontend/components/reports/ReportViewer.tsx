"use client";

import { Card } from "@/components/ui/Card";
import { Badge } from "@/components/ui/Badge";
import { formatDateTime } from "@/lib/utils/formatters";
import type { ReportResponse } from "@/lib/types";

interface ReportViewerProps {
  report: ReportResponse;
}

export function ReportViewer({ report }: ReportViewerProps) {
  const isDeterministic = report.provider === "deterministic_fallback";

  return (
    <div className="space-y-4">
      {isDeterministic ? (
        <div className="rounded-lg border border-blue-200 bg-blue-50 p-3">
          <p className="text-xs font-medium text-blue-800">
            Deterministic Evidence Summary — This report was generated from
            structured evidence and pre-computed analytics without an LLM.
            Interventionist review is still required.
          </p>
        </div>
      ) : (
        <div className="rounded-lg border border-amber-200 bg-amber-50 p-3">
          <p className="text-xs font-medium text-amber-800">
            AI-Generated Draft — This report was generated by AI and requires
            interventionist review before use.
          </p>
        </div>
      )}

      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <Badge variant="neutral">v{report.version}</Badge>
          {report.flagged && <Badge variant="error">Flagged</Badge>}
        </div>
        <span className="text-xs text-gray-400">
          Generated: {formatDateTime(report.generated_at)}
        </span>
      </div>

      {report.sections.map((section, i) => (
        <Card key={i}>
          <h3 className="mb-2 text-sm font-semibold text-gray-900">
            {section.heading}
          </h3>
          <div className="prose prose-sm max-w-none text-gray-700">
            <p className="whitespace-pre-wrap">{section.body}</p>
          </div>
          {section.evidence_refs && section.evidence_refs.length > 0 && (
            <div className="mt-2 border-t border-gray-100 pt-2">
              <p className="text-xs text-gray-400">
                Evidence references: {section.evidence_refs.length} source(s)
              </p>
            </div>
          )}
          {section.abstention_note && (
            <div className="mt-2 rounded bg-yellow-50 p-2">
              <p className="text-xs text-yellow-700">
                {section.abstention_note}
              </p>
            </div>
          )}
        </Card>
      ))}

      <Card title="Report Provenance">
        <dl className="divide-y divide-gray-100 text-sm">
          <div className="flex justify-between py-2">
            <dt className="text-gray-600">Provider</dt>
            <dd className="font-mono text-gray-900">{report.provider}</dd>
          </div>
          <div className="flex justify-between py-2">
            <dt className="text-gray-600">Model</dt>
            <dd className="font-mono text-gray-900">{report.model}</dd>
          </div>
          <div className="flex justify-between py-2">
            <dt className="text-gray-600">Prompt Version</dt>
            <dd className="font-mono text-gray-900">{report.prompt_version}</dd>
          </div>
          <div className="flex justify-between py-2">
            <dt className="text-gray-600">Report Version</dt>
            <dd className="font-mono text-gray-900">{report.version}</dd>
          </div>
          <div className="flex justify-between py-2">
            <dt className="text-gray-600">Validation</dt>
            <dd>
              <Badge variant={report.validation_passed ? "success" : "error"}>
                {report.validation_passed ? "Passed" : "Failed"}
              </Badge>
            </dd>
          </div>
          {report.flagged_reason && (
            <div className="flex justify-between py-2">
              <dt className="text-gray-600">Flag Reason</dt>
              <dd className="text-red-600">{report.flagged_reason}</dd>
            </div>
          )}
        </dl>
      </Card>
    </div>
  );
}
