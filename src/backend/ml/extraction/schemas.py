"""Extraction provider input/output contracts."""

from __future__ import annotations

import enum
from datetime import UTC, date, datetime
from typing import Literal, Optional

from pydantic import BaseModel, Field

from src.backend.schemas.observation_schema import (
    ContributorRole,
    Setting,
    StructuredObservation,
)


class SourceType(str, enum.Enum):
    CONVERSATIONAL = "conversational"
    CHAT_SEGMENT = "chat_segment"


class ExtractionRequest(BaseModel):
    """Input to the extraction provider.

    Carries the source text plus app-known metadata that must be preserved
    (not generated by the LLM) in the resulting StructuredObservation.
    """

    source_type: SourceType
    text: str = Field(min_length=1)

    # App-known metadata — passed through to the result
    child_id: str
    session_id: str
    contributor_role: ContributorRole
    observation_date: date
    setting: Setting

    # Source-specific context
    metadata: dict[str, object] = Field(default_factory=dict)

    # Goal context for extraction guidance
    goal_ids: list[str] = Field(default_factory=list)

    # Clarification history (for re-extraction after clarification)
    clarification_history: list[dict[str, str]] = Field(default_factory=list)


class ExtractionStatus(str, enum.Enum):
    SUCCESS = "success"
    PARTIAL = "partial"
    ABSTAINED = "abstained"
    FAILED = "failed"


class ExtractionResult(BaseModel):
    """Output from the extraction provider.

    Contains one or more structured observations extracted from the source,
    plus provider metadata. App-known fields are preserved from the request.
    """

    status: ExtractionStatus
    observations: list[StructuredObservation] = Field(default_factory=list)

    # Provider metadata
    provider: str
    model: str
    prompt_version: str
    schema_version: str = "1.0"
    generated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    # Clarification needed (when status is PARTIAL or ABSTAINED)
    clarification_questions: list[str] = Field(default_factory=list)

    # Raw provenance for audit
    raw_llm_response: Optional[str] = None

    # Processing metadata
    extraction_duration_ms: Optional[int] = None
    token_usage: Optional[dict[str, int]] = None


class ProviderInfo(BaseModel):
    """Metadata about an extraction provider."""

    name: str
    provider_type: Literal["temporary_llm", "finetuned_model"]
    model_id: str
    version: str
    is_available: bool = True
