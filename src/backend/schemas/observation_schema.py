"""Canonical structured observation field definitions from Technical Specification Section 4.1."""

from __future__ import annotations

import enum
from datetime import date
from typing import Optional

from pydantic import BaseModel, Field


class Domain(str, enum.Enum):
    SOCIAL_COMMUNICATION = "social_communication"
    LANGUAGE = "language"
    PLAY = "play"
    BEHAVIOR = "behavior"
    MOTOR = "motor"
    COGNITIVE = "cognitive"
    ADAPTIVE = "adaptive"
    SENSORY = "sensory"


class Modality(str, enum.Enum):
    VERBAL = "verbal"
    GESTURAL = "gestural"
    SIGN = "sign"
    AAC = "aac"
    WRITTEN = "written"
    MULTIMODAL = "multimodal"
    UNKNOWN = "unknown"


class PromptLevel(str, enum.Enum):
    INDEPENDENT = "independent"
    GESTURAL = "gestural"
    VERBAL = "verbal"
    MODEL = "model"
    PARTIAL_PHYSICAL = "partial_physical"
    FULL_PHYSICAL = "full_physical"
    UNKNOWN = "unknown"


class Outcome(str, enum.Enum):
    CORRECT = "correct"
    INCORRECT = "incorrect"
    APPROXIMATION = "approximation"
    NO_RESPONSE = "no_response"
    PARTIAL = "partial"
    UNKNOWN = "unknown"


class Setting(str, enum.Enum):
    HOME = "home"
    SCHOOL = "school"
    CLINIC = "clinic"
    COMMUNITY = "community"
    OTHER = "other"
    UNKNOWN = "unknown"


class ContributorRole(str, enum.Enum):
    INTERVENTIONIST = "interventionist"
    PARENT = "parent"
    TEACHER = "teacher"
    TRAINER = "trainer"
    EPA = "epa"
    SECONDARY_INTERVENTIONIST = "secondary_interventionist"


class StructuredObservation(BaseModel):
    """A single structured observation record.

    Fields split into three categories:
    - App-known metadata (passed through, never LLM-generated):
      child_id, session_id, contributor_role, observation_date, setting
    - LLM-extracted fields (derived from source text):
      domain, goal_context, behavior, modality, prompt_context, prompt_level,
      outcome, duration_seconds
    - Provider-generated metadata:
      confidence, abstention_reason
    """

    # App-known metadata — preserved from ExtractionRequest, not LLM-generated
    child_id: str
    session_id: str
    contributor_role: ContributorRole
    observation_date: date
    setting: Setting

    # LLM-extracted fields — derived from source text
    domain: Optional[Domain] = None
    goal_context: Optional[str] = None
    behavior: Optional[str] = None
    modality: Optional[Modality] = None
    prompt_context: Optional[str] = None
    prompt_level: Optional[PromptLevel] = None
    outcome: Optional[Outcome] = None
    duration_seconds: Optional[int] = Field(default=None, ge=0)

    # Provider-generated metadata
    confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0)
    abstention_reason: Optional[str] = None


# Fields the LLM is responsible for extracting from source text
LLM_EXTRACTED_FIELDS: frozenset[str] = frozenset({
    "domain",
    "goal_context",
    "behavior",
    "modality",
    "prompt_context",
    "prompt_level",
    "outcome",
    "duration_seconds",
})

# Fields that the application knows and passes into the extraction request
APP_KNOWN_FIELDS: frozenset[str] = frozenset({
    "child_id",
    "session_id",
    "contributor_role",
    "observation_date",
    "setting",
})

# Fields generated by the extraction provider itself
PROVIDER_GENERATED_FIELDS: frozenset[str] = frozenset({
    "confidence",
    "abstention_reason",
})
